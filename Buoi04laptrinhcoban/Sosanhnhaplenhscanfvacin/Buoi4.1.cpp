#include <iostream> 
using namespace std; // Dùng để nhập cin và cout
int main() {
	// Khai báo biến --> Biến chưa có giá 
	int a, b, c;
	float x, y, z;
	// Dung cin để nhập liệu 
	cin >> a; // Nhập giá trị cho biến a
	cin >> x >> y; // Nhập giá trị cho 2 biến 
	cin >> b >> z >> c; // Nhập giá trị cho 3 biến 
	
	return 0;
}
